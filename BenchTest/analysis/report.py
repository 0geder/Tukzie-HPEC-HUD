def _hours(t, tz_offset_h):
    from datetime import datetime, timezone, timedelta
    import matplotlib.dates as mdates
    tz = timezone(timedelta(hours=tz_offset_h))
    return mdates.date2num([datetime.fromtimestamp(x, tz).replace(tzinfo=None) for x in t])


def fig_session(dash, driving, segs, markers, path_base, tz_offset_h=2.0):
    """Vibration value and battery current against local time, driving shaded, markers dashed."""
    import matplotlib.dates as mdates
    x = _hours(dash.t, tz_offset_h)
    brk = np.flatnonzero((np.diff(dash.seq) != 1) | (np.diff(dash.boot) != 0)) + 1
    fig, axes = plt.subplots(2, 1, figsize=(W, 3.6), sharex=True)
    for ax, y, c, lab in ((axes[0], dash.vib, BLUE, "Vibration value, $\\sigma$ (m/s$^2$)"),
                          (axes[1], dash.i, VERM, "Battery current (A)")):
        xx = np.insert(x, brk, np.nan)
        yy = np.insert(y.astype(float), brk, np.nan)
        ax.plot(xx, yy, color=c, lw=0.5)
        ax.set_ylabel(lab)
        for a, b in segs:
            xa, xb = _hours([a, b + 1.0], tz_offset_h)
            ax.axvspan(xa, xb, color=GREEN, alpha=0.15, lw=0)
        for t, _txt in markers:
            ax.axvline(_hours([t], tz_offset_h)[0], color="black", lw=0.6, ls="--")
    axes[1].xaxis.set_major_formatter(mdates.DateFormatter("%H:%M"))
    axes[1].set_xlabel(f"Local time (UTC{tz_offset_h:+g})")
    fig.tight_layout(h_pad=0.4)
    return save_fig(fig, path_base)


def fig_pass_metric(rows, metric, ylabel, path_base):
    """One metric per pass, grouped by section: dots per pass and the section mean."""
    secs = sorted({r.get("section") or "all" for r in rows})
    fig, ax = plt.subplots(figsize=(W * 0.6, 2.6))
    for j, s in enumerate(secs):
        y = [r.get(metric) for r in rows if (r.get("section") or "all") == s]
        y = np.array([v for v in y if v is not None and np.isfinite(v)], float)
        if not len(y):
            continue
        xs = j + np.linspace(-0.15, 0.15, len(y)) if len(y) > 1 else np.array([j])
        ax.plot(xs, y, "o", ms=4, color=BLUE, mfc="white", mew=1.0)
        ax.plot([j - 0.25, j + 0.25], [y.mean()] * 2, color=VERM, lw=1.5)
    ax.set_xticks(range(len(secs)), secs)
    ax.set_xlabel("Road section")
    ax.set_ylabel(ylabel)
    fig.tight_layout()
    return save_fig(fig, path_base)


def fig_psd(stationary, road, lines_hz, path_base, band=(2.0, 40.0)):
    fig, ax = plt.subplots(figsize=(W, 2.8))
    for j, (name, (f, p)) in enumerate(stationary.items()):
        if len(f):
            ax.semilogy(f, p, color=SERIES[j % len(SERIES)], lw=0.9, label=f"stationary, {name}")
    for j, (name, (f, p)) in enumerate(road.items()):
        if len(f):
            ax.semilogy(f, p, color=GREY, lw=0.5, alpha=0.6, label="road passes" if j == 0 else None)
    for fl in lines_hz:
        ax.axvline(fl, color="black", lw=0.4, ls=":")
    ax.axvspan(0, band[0], color=GREY, alpha=0.08, lw=0)
    ax.set_xlabel("Frequency (Hz)")
    ax.set_ylabel("PSD of vertical acceleration ((m/s$^2$)$^2$/Hz)")
    ax.legend(loc="upper right")
    fig.tight_layout()
    return save_fig(fig, path_base)


def fig_roc(roc, chosen, path_base):
    fig, ax = plt.subplots(figsize=(W * 0.55, 2.6))
    fa = np.array([r["fa_per_km"] if r["fa_per_km"] is not None and np.isfinite(r["fa_per_km"])
                   else r["false_alarms"] for r in roc], float)
    dr = np.array([r["detection_rate"] for r in roc], float)
    o = np.argsort(fa)
    ax.step(fa[o], dr[o], where="post", color=BLUE, lw=1.2)
    cfa = chosen["fa_per_km"] if np.isfinite(chosen.get("fa_per_km", np.nan)) else chosen["false_alarms"]
    ax.plot([cfa], [chosen["detection_rate"]], "o", color=VERM, ms=6)
    ax.set_xlabel("False alarms per km on smooth road" if np.isfinite(roc[0].get("fa_per_km", np.nan))
                  else "False alarms on smooth passes (count)")
    ax.set_ylabel("Detection rate on obstacle passes")
    ax.set_ylim(-0.03, 1.03)
    fig.tight_layout()
    return save_fig(fig, path_base)


def fig_event(t, bp, ev, path_base):
    fig, ax = plt.subplots(figsize=(W * 0.55, 2.4))
    m = (t >= ev["t"] - 0.6) & (t <= ev["t"] + 0.6)
    ax.plot((t[m] - ev["t"]) * 1000, bp[m], color=BLUE, lw=0.9)
    ax.plot([(ev["t_drop"] - ev["t"]) * 1000, 0], [ev["drop"], ev["spike"]], "o", color=VERM, ms=4)
    ax.set_xlabel("Time from spike (ms)")
    ax.set_ylabel("Vertical acceleration, 2 to 40 Hz (m/s$^2$)")
    fig.tight_layout()
    return save_fig(fig, path_base)
