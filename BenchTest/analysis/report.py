def _fmt(v, digits=3):
    if v is None:
        return ""
    if isinstance(v, (bool, np.bool_)):
        return "yes" if v else "no"
    if isinstance(v, (int, np.integer)):
        return str(int(v))
    if isinstance(v, (float, np.floating)):
        if not math.isfinite(v):
            return ""
        return f"{v:.0f}" if abs(v) >= 10 ** digits else f"{v:.{digits}g}"
    if isinstance(v, (tuple, list)):
        return "; ".join(_fmt(x, digits) for x in v)
    return str(v)


_TEX = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
        "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def tex_escape(s):
    return "".join(_TEX.get(ch, ch) for ch in str(s))


def write_table(rows, path_base, columns=None, headers=None, digits=3):
    """rows: list of dicts. Writes <path_base>.csv (full precision) and <path_base>.tex (a tabular, no float)."""
    os.makedirs(os.path.dirname(path_base) or ".", exist_ok=True)
    if columns is None:
        columns = []
        for r in rows:
            for k in r:
                if k not in columns:
                    columns.append(k)
    headers = headers or {}
    with open(path_base + ".csv", "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(columns)
        for r in rows:
            w.writerow([_csv_val(r.get(c)) for c in columns])
    with open(path_base + ".tex", "w", encoding="utf-8") as f:
        f.write("% generated by BenchTest/analysis; do not edit by hand\n")
        f.write("\\begin{tabular}{" + "l" + "r" * (len(columns) - 1) + "}\n\\hline\n")
        f.write(" & ".join(tex_escape(headers.get(c, c)) for c in columns) + " \\\\ \\hline\n")
        for r in rows:
            f.write(" & ".join(tex_escape(_fmt(r.get(c), digits)) for c in columns) + " \\\\\n")
        f.write("\\hline\n\\end{tabular}\n")
    return path_base


def _csv_val(v):
    if isinstance(v, (float, np.floating)):
        return "" if not math.isfinite(v) else repr(float(v))
    if isinstance(v, (tuple, list)):
        return ";".join(str(_csv_val(x)) for x in v)
    return "" if v is None else v


def save_fig(fig, path_base):
    os.makedirs(os.path.dirname(path_base) or ".", exist_ok=True)
    fig.savefig(path_base + ".pdf")
    fig.savefig(path_base + ".png", dpi=200)
    plt.close(fig)
    return path_base


def _jsonable(o):
    if isinstance(o, dict):
        return {str(k): _jsonable(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_jsonable(v) for v in o]
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating, float)):
        return None if not math.isfinite(float(o)) else float(o)
    if isinstance(o, np.bool_):
        return bool(o)
    if isinstance(o, np.ndarray):
        return _jsonable(o.tolist())
    return o


def write_json(obj, path):
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(_jsonable(obj), f, indent=2)
    return path


